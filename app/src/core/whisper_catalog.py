def dtw_preset(info: dict | None) -> str | None:
    """Preset de whisper-cli -dtw (tiempos precisos por palabra) del modelo base: los
    nombres del catálogo coinciden con los de whisper.cpp cambiando "-" por "."."""
    base = (info or {}).get("model")
    return base.replace("-", ".") if base else None


