_CACHE = {}


def color_label(token: str) -> str:
    """El nombre traducido; un color que no esté en la lista (de un tema nuevo), con su clave."""
    if not _CACHE:
        _CACHE.update(_names())
    return _CACHE.get(token) or token.replace("_", " ").capitalize()
